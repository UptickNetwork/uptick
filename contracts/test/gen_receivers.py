#!/usr/bin/env python3
"""Compile the ERC721 receiver fixtures into Go test constants.

contracts/test/EVMReceiverFixtures.sol holds the hostile/observing receiver
contracts the ERC721 integration suite deploys into the real in-memory EVM.
This script compiles them with the same pinned solc as the shipped contracts
(0.8.28) and emits app/erc721_evm_receivers_gen_test.go, so the bytecode the
test deploys is traceable to readable Solidity instead of a hand-assembled hex
blob.

Usage:
    ./gen_receivers.py            # write the generated Go file
    ./gen_receivers.py --check    # exit 1 if the committed constants are stale
"""

import argparse
import json
import os
import shutil
import subprocess
import sys

SOLC_VERSION = "0.8.28"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_GO = os.path.join(ROOT, "..", "app", "erc721_evm_receivers_gen_test.go")
SOURCE = "test/EVMReceiverFixtures.sol"

# Contract name -> Go map key. The map key is what the tests look up.
FIXTURES = {
    "PlainContract": "Plain",
    "AcceptingReceiver": "Accepting",
    "RevertingReceiver": "Reverting",
    "GasBurningReceiver": "GasBurning",
    "ObservingReceiver": "Observing",
    "BurnOnReceiveReceiver": "BurnOnReceive",
}


def find_solc() -> str:
    for candidate in (os.environ.get("SOLC"), "solc"):
        if not candidate:
            continue
        path = shutil.which(candidate) if os.sep not in candidate else candidate
        if path and os.access(path, os.X_OK):
            return path
    sys.exit("error: solc not found; install solc 0.8.28 or set $SOLC")


def render() -> str:
    solc = find_solc()
    version = subprocess.run([solc, "--version"], capture_output=True, text=True).stdout
    found = version.split("Version: ")[-1].split("+")[0].strip()
    if found != SOLC_VERSION:
        sys.exit(f"error: solc {SOLC_VERSION} required, found {found}")

    proc = subprocess.run(
        [solc, "--combined-json", "bin", "--base-path", ".", SOURCE],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.exit(f"error: solc failed:\n{proc.stderr}")

    contracts = json.loads(proc.stdout)["contracts"]
    lines = [
        "// Code generated by contracts/test/gen_receivers.py. DO NOT EDIT.",
        "//",
        f"// Creation bytecode for the receiver fixtures in {SOURCE},",
        f"// compiled with solc {SOLC_VERSION}. Regenerate with:",
        "//",
        "//     cd contracts/test && ./gen_receivers.py",
        "",
        "package app",
        "",
        "// erc721ReceiverFixtures maps a fixture name to the creation bytecode the",
        "// integration test deploys. These are hostile/observing ERC721 receivers,",
        "// never part of the node binary: the file is a _test.go so it cannot be",
        "// compiled into uptickd.",
        "var erc721ReceiverFixtures = map[string]string{",
    ]

    entries = []
    for contract, key in sorted(FIXTURES.items(), key=lambda kv: kv[1]):
        match = [k for k in contracts if k.endswith(":" + contract)]
        if len(match) != 1:
            sys.exit(f"error: expected exactly one {contract}, got {match}")
        binary = contracts[match[0]]["bin"]
        if not binary:
            sys.exit(f"error: {contract} produced no bytecode")
        entries.append((f'"{key}":', f'"0x{binary}"'))

    # gofmt aligns the values of a composite literal into a column. Doing that
    # padding here keeps the generated file gofmt-clean without shelling out to
    # `gofmt` (the CI reproducibility job has solc, not necessarily Go), and
    # --check compares bytes, so the two must agree exactly.
    width = max(len(field) for field, _ in entries)
    for field, value in entries:
        lines.append(f"\t{field}{' ' * (width - len(field) + 1)}{value},")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    wanted = render()
    current = open(OUT_GO).read() if os.path.exists(OUT_GO) else None

    if current == wanted:
        print("ok: erc721_evm_receivers_gen_test.go is up to date")
        return 0
    if args.check:
        sys.exit("error: erc721_evm_receivers_gen_test.go is stale; run gen_receivers.py")

    with open(OUT_GO, "w") as fh:
        fh.write(wanted)
    print(f"wrote {os.path.relpath(OUT_GO, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
